const features = rows
  .map((row) => Object.fromEntries(fields.map((f, i) => [f, row[i]])))
  .map((x) => ({
    ...x,
    functionalDifference: x.referenceBehavior,
    referenceObservedAt: observed,
    referenceEvidence: "unavailable_private_or_network_blocked",
  }));
const allowed = new Set([
  "complete",
  "partial",
  "missing",
  "intentionally different",
  "blocked",
  "excluded",
]);
if (
  new Set(features.map((x) => x.id)).size !== features.length ||
  features.some((x) => !allowed.has(x.state))
)
  throw new Error("invalid parity matrix");
const totals = Object.fromEntries(
  [...allowed].map((s) => [s, features.filter((x) => x.state === s).length]),
);
